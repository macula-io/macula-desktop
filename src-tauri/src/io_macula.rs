/// realm_key is io.macula's public realm key as carried on the wire.
pub fn realm_key() -> Vec<u8> {
    let hex: String = REALM_KEY_HEX.concat();
    (0..hex.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&hex[i..i + 2], 16).expect("REALM_KEY_HEX is hex"))
        .collect()
}
